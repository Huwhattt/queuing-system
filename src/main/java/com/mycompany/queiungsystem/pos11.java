    private void removeitemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeitemActionPerformed
    int selectedRow = jTable1.getSelectedRow();

    
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Select an item to remove");
        return;
    }

    int currentQty = (int) model.getValueAt(selectedRow, 0); 
    double currentPrice = (double) model.getValueAt(selectedRow, 2); 
    double unitPrice = currentPrice / currentQty;

    while (true) {
        String input = JOptionPane.showInputDialog(this, 
                          "How many items you want to delete?");
        
        if (input == null) return; 

        try {
            int qtyToRemove = Integer.parseInt(input);

            if (qtyToRemove <= 0) {
                JOptionPane.showMessageDialog(this, "Enter a positive number.");
                continue;
            }

            if (qtyToRemove > currentQty) {
                JOptionPane.showMessageDialog(this, "Invalid Amount");
                continue; 
            }

           
            if (qtyToRemove == currentQty) {
                model.removeRow(selectedRow);
            } else {
                int newQty = currentQty - qtyToRemove;
                model.setValueAt(newQty, selectedRow, 0);
                model.setValueAt(newQty * unitPrice, selectedRow, 2);
            }

            calculateTotal(); 
            break; 

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Enter a valid number.");
        }
    }

    }//GEN-LAST:event_removeitemActionPerformed

