    private void calculateTotal() {
    double total = 0;

    for (int i = 0; i < model.getRowCount(); i++) {
        double price = (double) model.getValueAt(i, 2); 
        total += price;
    }

    TOTAL.setText(String.format("%.2f", total)); 
}
    
    

