        if (selectedRow != -1) {
            Object productObj = jTable1.getValueAt(selectedRow, 0);
            Object qtyObj = jTable1.getValueAt(selectedRow, 2);

            if (productObj != null) {
                item.setText(productObj.toString());
            }

            if (qtyObj != null) {
                qty.setText(qtyObj.toString());
            }
        }
   
