    private void updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateActionPerformed
        int selectedRow = jTable1.getSelectedRow();
         if (selectedRow == -1) {
             JOptionPane.showMessageDialog(this, "Please select a product first!");
             return;
         }

         String product = jTable1.getValueAt(selectedRow, 0).toString();
         int currentQty = Integer.parseInt(jTable1.getValueAt(selectedRow, 2).toString());

         int newQty;
         try {
             newQty = Integer.parseInt(qty.getText().trim()); // from JTextField
         } catch (NumberFormatException e) {
             JOptionPane.showMessageDialog(this, "Invalid number!");
             return;
         }

         if (newQty < currentQty) {
             JOptionPane.showMessageDialog(this, "Quantity cannot be less than current stock!");
             return;
         }

         // ✅ update both map and table
         InventoryData.quantities.put(product, newQty);
         jTable1.setValueAt(newQty, selectedRow, 2);

         JOptionPane.showMessageDialog(this, "Inventory updated!");
    }//GEN-LAST:event_updateActionPerformed

