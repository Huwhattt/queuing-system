    private void calculateTotal() {
    double Total = 0;

    for (int i = 0; i < model.getRowCount(); i++) {
        double price = (double) model.getValueAt(i, 2); 
        Total += price;
    }

    total.setText(String.format("%.2f", Total)); 
}
    
    public void addToTable(String itemName, double unitPrice) {
   for (int i = 0; i < model.getRowCount(); i++) {
        String existingItem = (String) model.getValueAt(i, 1); 
        if (existingItem.equals(itemName)) {
            int currentQty = (int) model.getValueAt(i, 0);
            currentQty++;
            model.setValueAt(currentQty, i, 0);

            double newPrice = currentQty * unitPrice;
            model.setValueAt(newPrice, i, 2);

            calculateTotal();
            return;
        }
    }

    model.addRow(new Object[]{1, itemName, unitPrice});
    calculateTotal();
}

