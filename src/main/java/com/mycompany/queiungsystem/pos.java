    private void payActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_payActionPerformed
        
        String paymentInput = payment.getText().trim();
        if (paymentInput.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Input amount");
            hasPaid=false;
            return;
        }
        
    String transaction = combobox.getSelectedItem().toString().trim();
        if (transaction.equalsIgnoreCase("Service Type")) {
            JOptionPane.showMessageDialog(this, "Select a Type of Service");
            hasPaid=false;
            return;
        }

     try {
        double Total = Double.parseDouble(total.getText());
        double Payment = Double.parseDouble(payment.getText());
        
        if (Payment < Total) {
            JOptionPane.showMessageDialog(this, "Insufficient Payment!");
            hasPaid=false;
            return;
        }
        if (Payment >= Total) {
            double change = Payment - Total;
            sukli.setText(String.format("%.2f", change));
            hasPaid=true;
            JOptionPane.showMessageDialog(this, "Payment Successful!");
            
        }   
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Enter a valid payment amount.");
    }
     
     
    }//GEN-LAST:event_payActionPerformed

    private void removeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeActionPerformed
       int selectedRow = jTable1.getSelectedRow();

    
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Select an item to remove");
        return;
    }

    int currentQty = (int) model.getValueAt(selectedRow, 0); 
    double currentPrice = (double) model.getValueAt(selectedRow, 2); 
    double unitPrice = currentPrice / currentQty;

    while (true) {
        String input = JOptionPane.showInputDialog(this, 
                          "How many items you want to delete?");
        
        if (input == null) return; 

        try {
            int qtyToRemove = Integer.parseInt(input);

            if (qtyToRemove <= 0) {
                JOptionPane.showMessageDialog(this, "Enter a positive number.");
                continue;
            }

            if (qtyToRemove > currentQty) {
                JOptionPane.showMessageDialog(this, "Invalid Amount");
                continue; 
            }

           
            if (qtyToRemove == currentQty) {
                model.removeRow(selectedRow);
            } else {
                int newQty = currentQty - qtyToRemove;
                model.setValueAt(newQty, selectedRow, 0);
                model.setValueAt(newQty * unitPrice, selectedRow, 2);
            }

            calculateTotal(); 
            break; 

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Enter a valid number.");
        }
    }
    }//GEN-LAST:event_removeActionPerformed

